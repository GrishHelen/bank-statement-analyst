def with_statement_context(prompt: str, statement_info: str | None) -> str:
    """Стабильный контекст: какая выписка загружена и какой у неё период."""
    if statement_info:
        return prompt + f"\nЗагруженная выписка: {statement_info}.\n"
    return prompt + "\nВыписка пока не загружена: попроси пользователя выполнить /load <путь к CSV>.\n"
